#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define	MAXSTRSIZE	0x10

int main(int argc, char **argv)	/* Host port: int, was void */
{
	const char *input_name;
	long size;
	int i, j, nstr, remaining, count, write_failed;
	unsigned char bytes[MAXSTRSIZE];
	FILE	*inf, *outf;

	if (argc != 3) {
		fprintf(stderr, "usage: %s <inputfile> <outputfile>\n", argv[0]);
		exit(1);
	}

	if ((inf = fopen(argv[1],"rb")) == NULL) {
		fprintf(stderr, "%s Could not open input file %s for reading\n", argv[0], argv[1]);
		exit(1);
	}

	/* The generated Helios program stores the firmware length in a WORD. */
	if (fseek(inf, 0, SEEK_END) != 0 || (size = ftell(inf)) <= 0 ||
	    size > 0x7fffffffL || fseek(inf, 0, SEEK_SET) != 0) {
		fprintf(stderr, "%s: expected a nonempty, seekable firmware file of signed WORD length: %s\n",
		        argv[0], argv[1]);
		fclose(inf);
		return 1;
	}
	remaining = (int)size;
	nstr = 1 + (remaining - 1) / MAXSTRSIZE;

	if ((outf = fopen(argv[2],"w")) == NULL) {
		perror(argv[2]);
		fclose(inf);
		return 1;
	}

	/* GNU make may pass an absolute VPATH name for the firmware. */
	input_name = strrchr(argv[1], '/');
	input_name = input_name ? input_name + 1 : argv[1];

	/* Generate the headers */
	fprintf(outf, "/*\n");
	fprintf(outf, " * DO NOT MODIFY:\n");
	fprintf(outf, " * THIS FILE WAS AUTO-GENERATED BY %s from %s\n", argv[0], input_name);
	fprintf(outf, " */\n\n");
	fprintf(outf, "WORD squirtdata(WORD link)\n");
	fprintf(outf, "/* \n");
	fprintf(outf, " *\t'squirt' the B422 TRAM driver code down \n");
	fprintf(outf, " *\tthe specified link. This will then execute\n");
	fprintf(outf, " *\tand expect us to be an i-server capable of\n");
	fprintf(outf, " *\tgiving it's board size.\n");
	fprintf(outf, " */\n");
	fprintf(outf, "{\n");

	fprintf(outf, "\tBYTE\t\ts[11];\n");
	fprintf(outf, "\tWORD\t\tn;\n");
	fprintf(outf, "\tINT16\t\ti16;\n");

	/* Generate the variable initialisation */
	fprintf(outf, "\tWORD\t\tsize = %ld;\n", size);
	fprintf(outf, "\tWORD\t\tnstr = %d;\n", nstr);
	fprintf(outf, "\tchar *\t\tdata[%d];\n", nstr);
	fprintf(outf, "\n");
	fprintf(outf, "\t/* Initialise the strings */\n");

	for (i = 0; i < nstr; i++) {
		count = remaining < MAXSTRSIZE ? remaining : MAXSTRSIZE;
		if (fread(bytes, 1, count, inf) != (size_t)count) {
			fprintf(stderr, "%s: could not read all firmware bytes from %s\n",
			        argv[0], argv[1]);
			fclose(inf);
			fclose(outf);
			return 1;
		}
		fprintf(outf, "\tdata[%d] = \t\"", i);
		for (j = 0; j < count; j++)
			fprintf(outf, "\\x%02x", (unsigned int)bytes[j]);
		fprintf(outf, "\";\n");
		remaining -= count;
	}
	fprintf(outf, "\n");

	/* Generate the code to send the data */
	fprintf(outf, "\t/* Send the completed data */\n");
	fprintf(outf, "\tfor (n=0; n<(nstr-1); n++) {\n");
	fprintf(outf, "\t\tLinkOut(%d, link, data[n], LINKTIMEOUT);\n", MAXSTRSIZE);
	fprintf(outf, "\t\tsize -= %d;\n", MAXSTRSIZE);
	fprintf(outf, "\t}\n");
	fprintf(outf, "\n");
	fprintf(outf, "\t/* Send the last string */\n");
	fprintf(outf, "\tLinkOut(size, link, data[n], LINKTIMEOUT);\n");
	fprintf(outf, "\n");

	/* Create the final bits of code */
	fprintf(outf, "\t/* It thinks we're an i-server, so fool it! */\n");
	fprintf(outf, "\tLinkIn(sizeof(i16), link, &i16, LINKTIMEOUT);\n");
	fprintf(outf, "\tLinkIn(i16, link, data, LINKTIMEOUT);\n");
	fprintf(outf, "\n");
	fprintf(outf, "\t/* Magic! */\n");
	fprintf(outf, "\ts[0] = 9; s[1] = 0; s[2] = 0; s[3] = 6;\ts[4] = 0;\n");
	fprintf(outf, "\ts[5] = '#'; s[6] = '1'; s[7] = s[8] = s[9] = s[10] = '0';\n");
	fprintf(outf, "\n");
	fprintf(outf, "\t/* make the B422 a happy TRAM */\n");
	fprintf(outf, "\tLinkOut(11, link, s, LINKTIMEOUT);\n");
	fprintf(outf, "\n");
	fprintf(outf, "\treturn(TRUE);\n");
	fprintf(outf, "\n");
	fprintf(outf, "}\n");

	fclose(inf);
	write_failed = ferror(outf);
	if (fclose(outf) != 0 || write_failed) {
		fprintf(stderr, "%s: could not write %s\n", argv[0], argv[2]);
		return 1;
	}
	return 0;
}

